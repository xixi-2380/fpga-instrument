"""Build compact bilingual UI ROM/header from licensed, committed font subsets.
Run from any directory. Preserves the original 16384 English ROM words exactly.
Chinese styles: brush (British/Easter), elegant serif (cat), playful (capybara).
"""
from pathlib import Path
import json,hashlib
from PIL import Image,ImageDraw,ImageFont
from fontTools.ttLib import TTFont
R=Path(__file__).resolve().parents[1]
def main():
 translations=json.loads((R/'assets/ui_language.json').read_text())
 chars=sorted(set(''.join(translations.values()))-set(chr(c) for c in range(128)))
 assert len(chars)<=128
 codes={ch:128+i for i,ch in enumerate(chars)}
 def encoded(t):return bytes(ord(ch) if ord(ch)<128 else codes[ch] for ch in t)
 def literal(t):return f"320'h{encoded(t).hex()}"
 words=[int(x,16) for x in (R/'src/rom/theme_font.hex').read_text().split()][:16384]
 assert len(words)==16384
 base=len(words);style_words=len(chars)*16
 fonts=['HighWaterChineseBrush.ttf','HighWaterChineseElegant.ttf','HighWaterChinesePlayful.ttf']
 manifest={'glyphs':len(chars),'glyph_order':''.join(chars),'english_words':16384,'english_sha256':hashlib.sha256(bytes().join(w.to_bytes(2,'big') for w in words)).hexdigest(),'fonts':[]}
 for fn in fonts:
  path=R/'assets/fonts'/fn;tt=TTFont(path);cmap=tt.getBestCmap()
  assert all(ord(c) in cmap for c in chars),f'missing actual glyph in {fn}'
  manifest['fonts'].append({'file':str(path.relative_to(R)),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
  font=ImageFont.truetype(str(path),15)
  for ch in chars:
   box=font.getbbox(ch);g=Image.new('L',(box[2]-box[0],box[3]-box[1]));ImageDraw.Draw(g).text((-box[0],-box[1]),ch,font=font,fill=255)
   g.thumbnail((16,15),Image.Resampling.LANCZOS);im=Image.new('L',(16,16));im.paste(g,((16-g.width)//2,(16-g.height)//2))
   rows=[sum(1<<(15-x) for x in range(16) if im.getpixel((x,y))>=70) for y in range(16)]
   assert any(rows),f'empty glyph {ch}';words+=rows
 title_base=len(words)
 for fn in fonts:
  font=ImageFont.truetype(str(R/'assets/fonts'/fn),48);t=translations['TITLE'];box=font.getbbox(t)
  g=Image.new('L',(box[2]-box[0],box[3]-box[1]));ImageDraw.Draw(g).text((-box[0],-box[1]),t,font=font,fill=255)
  g.thumbnail((370,60),Image.Resampling.LANCZOS);im=Image.new('L',(384,64));im.paste(g,((384-g.width)//2,(64-g.height)//2))
  for y in range(64):
   for tile in range(48):words.append(sum(min(3,(im.getpixel((tile*8+x,y))+42)//85)<<(14-2*x) for x in range(8)))
 assert len(words)<=32768;used=len(words);words += [0]*(32768-len(words))
 (R/'src/rom/theme_font.hex').write_text('\n'.join(' '.join(f'{w:04x}' for w in words[i:i+32]) for i in range(0,len(words),32))+'\n')
 h=['// Generated by scripts/gen_ui_language.py; byte IDs, not UTF-8 in RTL.',f'localparam integer ZH_GLYPH_BASE={base},ZH_STYLE_WORDS={style_words},ZH_GLYPHS={len(chars)},ZH_TITLE_BASE={title_base};']
 for name,key in [('ZH_CHINESE','CHINESE'),('ZH_PEAK','PEAK'),('ZH_VOICES','VOICES')]:h.append(f"localparam [{len(translations[key])*8-1}:0] {name}={len(translations[key])*8}'h{encoded(translations[key]).hex()};")
 h+=['function automatic [325:0] ui_word(input [5:0] id,input zh);',' begin case(id)']
 for i,(en,zh) in enumerate(list(translations.items())[:-4]):h.append(f"  6'd{i}:ui_word=zh ? {{6'd{len(zh)},{literal(zh)}}} : {{6'd{len(en)},{literal(en)}}}; // {en}: {zh}")
 h+=['  default:ui_word=0;',' endcase end','endfunction']
 (R/'src/config/ui_language.svh').write_text('\n'.join(h)+'\n')
 manifest.update({'used_words':used,'rom_words':len(words),'rom_bits':len(words)*16,'glyph_base':base,'title_base':title_base})
 (R/'assets/ui_language_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
 print(json.dumps({'glyphs':len(chars),'used_words':used,'rom_words':len(words)}))
if __name__=='__main__':main()
